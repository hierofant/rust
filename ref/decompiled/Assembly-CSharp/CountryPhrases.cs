	public static IReadOnlyDictionary<string, Translate.Phrase> AllCountries => _phrases;

	public static Translate.Phrase Get(string code)
	{
		if (string.IsNullOrEmpty(code))
		{
			if (debug_browser_codes)
			{
				Debug.Log("Country code was null or empty");
			}
			return Country_UNKNOWN;
		}
		if (_phrases.TryGetValue(code, out var value))
		{
			return value;
		}
		if (debug_browser_codes)
		{
			Debug.Log("Couldn't find country phrase for code '" + code + "'");
		}
		return Country_UNKNOWN;
	}
